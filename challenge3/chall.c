// Anti-debug 1: check ptrace (Linux) / sysctl (macOS)
#ifdef __APPLE__
#include <sys/types.h>
#include <sys/sysctl.h>
static int being_debugged(void) {
    int mib[4] = {CTL_KERN, KERN_PROC, KERN_PROC_PID, getpid()};
    struct kinfo_proc info = {0};
    size_t size = sizeof(info);
    sysctl(mib, 4, &info, &size, NULL, 0);
    return (info.kp_proc.p_flag & P_TRACED) != 0;
}
#else
#include <sys/ptrace.h>
static int being_debugged(void) {
    return ptrace(PTRACE_TRACEME, 0, 0, 0) == -1;
}
#endif

// Anti-debug 2: timing check (debuggers slow execution)
#include <time.h>
static int timing_check(void) {
    struct timespec t1, t2;
    clock_gettime(CLOCK_MONOTONIC, &t1);
    volatile int x = 0;
    for (int i = 0; i < 1000000; i++) x += i;
    clock_gettime(CLOCK_MONOTONIC, &t2);
    long elapsed_ms = (t2.tv_sec - t1.tv_sec)*1000 +
                      (t2.tv_nsec - t1.tv_nsec)/1000000;
    return elapsed_ms > 2000; // suspicious if > 2 seconds
}

