// Table is rebuilt at runtime into this buffer
static uint8_t MATRIX[256];

static const uint8_t TARGET[] = {
    0x87,0x90,0x0F,0xFA,0x4D,0xC2,0xF1,0x09,0xFA,0xCE,0x90,0xF9
};
#define FLAG_LEN 12

// Fake check — red herring visible in strings/Ghidra
static int fake_validate(const char *s) {
    uint32_t h = 5381;
    while (*s) h = ((h << 5) + h) ^ (uint8_t)*s++;
    return h == 0xDEADBEEF;
}

__attribute__((constructor))
static void init_table(void) {
    // Reassemble table at runtime — not visible as one blob statically
    memcpy(MATRIX,     TABLE_LO, 128);
    memcpy(MATRIX+128, TABLE_HI, 128);
}

int main(void) {
    // Anti-debug checks
    if (being_debugged()) { puts("Wrong."); return 1; }
    if (timing_check())   { puts("Wrong."); return 1; }

    char input[64] = {0};
    printf("Enter flag: ");
    scanf("%32s", input);

    // Red herring call — confuses control flow analysis
    (void)fake_validate(input);

    uint8_t out[FLAG_LEN];
    for (int i = 0; i < FLAG_LEN; i++)
        out[i] = MATRIX[(uint8_t)input[i]];

    if (memcmp(out, TARGET, FLAG_LEN) == 0)
        printf("Eclipse{%s}\n", input);
    else
        puts("Wrong.");
    return 0;
}